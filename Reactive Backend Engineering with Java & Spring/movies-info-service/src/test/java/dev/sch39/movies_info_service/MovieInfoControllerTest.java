package dev.sch39.movies_info_service;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;

import java.util.List;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.test.context.SpringBootTest.WebEnvironment;
import org.springframework.boot.webtestclient.autoconfigure.AutoConfigureWebTestClient;
import org.springframework.test.web.reactive.server.WebTestClient;

@SpringBootTest(webEnvironment = WebEnvironment.RANDOM_PORT, properties = "spring.mongodb.database=movies_info_test")
@AutoConfigureWebTestClient
class MovieInfoControllerTest {

    private static final String URL = "/v1/movie-info";

    @Autowired
    private WebTestClient client;

    @Autowired
    private MovieInfoRepository repository;

    @BeforeEach
    void cleanCollection() {
        repository.deleteAll().block();
    }

    @Test
    void createThenFindById() {
        MovieInfo saved = client.post().uri(URL)
                .bodyValue(new MovieInfo(null, "Batman Begins", 2005, List.of("Christian Bale")))
                .exchange()
                .expectStatus().isCreated()
                .expectBody(MovieInfo.class).returnResult().getResponseBody();

        assertNotNull(saved.movieInfoId(), "id must be generated by MongoDB");
        MovieInfo found = client.get().uri(URL + "/{id}", saved.movieInfoId())
                .exchange()
                .expectStatus().isOk()
                .expectBody(MovieInfo.class).returnResult().getResponseBody();

        System.out.println("saved=" + saved);
        System.out.println("found=" + found);
        assertEquals(saved, found, "found vs saved");
    }

    @Test
    void updateReplacesFieldsAndKeepsId() {
        MovieInfo saved = repository.save(new MovieInfo(null, "Dark Knight", 2007, List.of("Heath Ledger"))).block();

        MovieInfo updated = client.put().uri(URL + "/{id}", saved.movieInfoId())
                .bodyValue(new MovieInfo(null, "The Dark Knight", 2008, List.of("Heath Ledger")))
                .exchange()
                .expectStatus().isOk()
                .expectBody(MovieInfo.class).returnResult().getResponseBody();

        System.out.println("updated=" + updated);
        System.out.println("count=" + repository.count().block());
        assertEquals(saved.movieInfoId(), updated.movieInfoId(), "id must stay the same");
        assertEquals(2008, updated.year(), "year");
        assertEquals(1L, repository.count().block(), "document count");
    }

    @Test
    void deletedIdReturnsNotFound() {
        MovieInfo saved = repository.save(new MovieInfo(null, "Inception", 2010, List.of("Leonardo DiCaprio"))).block();

        client.delete().uri(URL + "/{id}", saved.movieInfoId()).exchange().expectStatus().isNoContent();

        System.out.println("count after delete=" + repository.count().block());
        client.get().uri(URL + "/{id}", saved.movieInfoId()).exchange().expectStatus().isNotFound();
        client.put().uri(URL + "/{id}", saved.movieInfoId())
                .bodyValue(new MovieInfo(null, "Inception", 2010, List.of("Leonardo DiCaprio")))
                .exchange().expectStatus().isNotFound();
        assertEquals(0L, repository.count().block(), "PUT on a missing id must not upsert");
    }
}